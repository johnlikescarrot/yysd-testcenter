/** Điền biến vào chuỗi, giữ nguyên placeholder khi thiếu giá trị. */
export function t(key, values = {}) {
  const template = STRINGS[key];
  if (template === undefined) return key;
  return template.replace(/\{(\w+)\}/g, (_match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`);
}

/** Phát hiện ký tự Hán còn sót lại (nội dung chưa được Việt hoá). */
export function hasCjk(value) {
  return /[\u3400-\u9fff]/.test(String(value));
}

/** Bảo vệ bản địa hoá: ném lỗi nếu còn tiếng Trung. */
export function assertVietnamese(value) {
  if (hasCjk(value)) throw new Error('Nội dung chưa được Việt hoá');
  return value;
}
