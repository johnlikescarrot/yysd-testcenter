export const LOCALES = Object.keys(STRINGS);

/** Thay {placeholder} bằng giá trị trong vars. */
export function interpolate(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  );
}

/** Tạo bộ dịch: tra locale → vi → key. */
export function createI18n(initialLocale = DEFAULT_LOCALE) {
  let locale = LOCALES.includes(initialLocale) ? initialLocale : DEFAULT_LOCALE;

  function t(key, vars) {
    const table = STRINGS[locale];
    const fallback = STRINGS[DEFAULT_LOCALE];
    const template = table[key] ?? fallback[key] ?? key;
    return interpolate(template, vars);
  }

  return {
    get locale() {
      return locale;
    },
    t,
    setLocale(next) {
      if (LOCALES.includes(next)) locale = next;
      return locale;
    },
    available: LOCALES
  };
}
