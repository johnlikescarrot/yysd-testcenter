import { writeFile } from 'node:fs/promises';
import { loadWorkbooks } from './workbooks.mjs';

// Stable keys survive edits and reordering; the HTML workbooks are the only
// hand-maintained source of the terms, meanings and example sentences.
const books = await loadWorkbooks('listening');
const output = new URL('../ielts-vi/assets/deck.js', import.meta.url);
const groups = books.map(({ topic, number, rows }) => {
  const cards = rows.map(({ term, meaning, example }) => {
    const id = `${number}-${term.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-')}`;
    return `    ${JSON.stringify([id, term, meaning, example])}`;
  });
  return `  [${JSON.stringify(topic)}, [\n${cards.join(',\n')}\n  ]]`;
});
await writeFile(output, `// Generated by quality/make-deck.mjs from the localized listening workbooks.\nexport const decks = [\n${groups.join(',\n')}\n];\n`);
