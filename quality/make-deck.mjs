// The existing YYSD word lists are the editorial source. Extract literal fields,
// not executable HTML or scripts. Stable keys survive edits and reordering.
import { readdir, readFile, writeFile } from 'node:fs/promises';

const dir = new URL('../library/study/vocab-special-listening/', import.meta.url);
const output = new URL('../ielts-vi/assets/deck.js', import.meta.url);
const files = (await readdir(dir)).filter((name) => /^listening-vocab-\d+-[\w-]+\.html$/.test(name)).sort();
const groups = [];
for (const file of files) {
  const source = await readFile(new URL(file, dir), 'utf8');
  const [, topic] = source.match(/name="exam:title" content="Bài \d+ · ([^"]+)"/) ?? [];
  const [, block] = source.match(/const wordData = \[([\s\S]*?)\n\];/) ?? [];
  if (!topic || !block) throw new Error(`Missing Vietnamese title or wordData in ${file}`);
  const group = [];
  for (const line of block.split('\n').filter((row) => row.trimStart().startsWith('{'))) {
    const field = (name) => {
      const match = new RegExp(`\\b${name}:\\s*'((?:\\\\.|[^'\\\\])*)'`).exec(line);
      if (!match) throw new Error(`Missing literal ${name} in ${file}: ${line}`);
      return match[1].replaceAll("\\'", "'");
    };
    const term = field('word');
    const meaning = field('meaning');
    const sentence = field('example');
    if (/\p{Script=Han}/u.test(meaning) || !meaning || !sentence) throw new Error(`Incomplete card: ${term}`);
    const id = `${file.split('-')[2]}-${term.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-')}`;
    group.push([id, term, meaning, sentence]);
  }
  if (group.length < 5) throw new Error(`Not enough cards in ${file}`);
  groups.push([topic, group]);
}
if (!groups.length) throw new Error('No listening workbooks found');
const count = groups.flatMap(([, group]) => group).length;
const rows = groups.map(([topic, group]) => `  [${JSON.stringify(topic)}, [\n${group.map((row) => `    ${JSON.stringify(row)}`).join(',\n')}\n  ]]`);
await writeFile(output, `// Generated by quality/make-deck.mjs from the localized listening workbooks.\nexport const decks = [\n${rows.join(',\n')}\n];\n`);
console.log(`${count} vocabulary cards from ${groups.length} existing workbooks.`);
