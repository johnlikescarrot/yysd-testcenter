function sentenceEn(ctx) {
  var s = String(ctx || "");
  for (var i = 0; i < SENTENCE_KW.length; i++) {
    if (SENTENCE_KW[i][0].test(s)) return SENTENCE_KW[i][1];
  }
  var first = s.replace(/\s+/g, " ").trim().split(/[.!?]/)[0];
  if (first.length > 34) first = first.slice(0, 34).replace(/\s+\S*$/, "");
  return titleCase(first) || "Sentence";
}

function titleEn(skill, task) {
  if (skill === "speaking") return speakEn(task.instruction || task.stem || task.title || "");
  if (skill === "writing") return writeEn(task);
  if (task.title &&!/^choose a response$/i.test(task.title)) return task.title;
  if (task.questions && task.questions[0]) return "Q" + task.questions[0].id;
  return task.title || task.type || "Task";
}

function phraseZh(en) {
  var s = String(en || "").trim();
  if (EXACT[s]) return EXACT[s];
  var low = s.toLowerCase();
  for (var i = 0; i < PHRASE.length; i++) {
    if (low.indexOf(PHRASE[i][0]) >= 0) return PHRASE[i][1];
  }
  var words = low.replace(/[^a-z0-9\s-]/g, " ").split(/\s+/).filter(Boolean);
  var zh = [];
  var hit = 0;
  words.forEach(function (w) {
    if (WORD[w]) { zh.push(WORD[w]); hit += 1; }
  });
  if (hit >= Math.min(2, words.length) && zh.length) return zh.join("");
  return s;
}

function titleZh(en) {
  if (EXACT[en]) return EXACT[en];
  var key = String(en || "");
  var hit = Object.keys(EXACT).filter(function (k) { return k.toLowerCase() === key.toLowerCase(); })[0];
  return hit? EXACT[hit]: phraseZh(en);
}

var LISTEN_CODE = {
  choose_response: "LR",
  conversation: "C",
  announcement: "A",
  lecture: "T"
};

function pad2(n) { return (n < 10? "0": "") + n; }

function assignListenCodes(items) {
  var groups = {};
  items.forEach(function (it, idx) {
    if (it.skill!== "listening") return;
    var k = it.paperId + "|" + it.type;
    if (!groups[k]) groups[k] = [];
    groups[k].push(it);
  });
  Object.keys(groups).forEach(function (k) {
    groups[k].sort(function (a, b) { return a.taskIndex - b.taskIndex; });
    var prefix = LISTEN_CODE[groups[k][0].type] || "Q";
    groups[k].forEach(function (it, i) {
      it.listenCode = prefix + pad2(i + 1);
    });
  });
}

