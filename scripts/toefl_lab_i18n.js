  if (/tutorial on how to register/i.test(s)) return "Course Registration Tutorial";
  if (/show new students around the university library/i.test(s)) return "Library Tour";
  if (/online learning plat/i.test(s)) return "Online Learning Platform";
  if (/travel agency/i.test(s)) return "Travel Agency";
  if (/listen to the \w+ and repeat/i.test(s) &&!/working|volunteer|trained|assist/i.test(s)) return "Listen And Repeat";
  var m = s.match(/(?:experiences with|views on|questions about|study about|interview about|researcher about|research study(?: at your university)? about|research interview about|investigating people['’]?s experiences with|signed up for a study[^.]*?(?:about|investigating)|opinions on)\s+([^.,]+)/i);
  if (m) {
    var topic = m[1]
      .replace(/ at your university.*$/i, "")
      .replace(/\s+you will.*$/i, "")
      .replace(/\s+the researcher.*$/i, "")
      .replace(/\s+and its implementation.*$/i, "")
      .replace(/^people'?s experiences with /i, "")
      .replace(/^how people /i, "")
      .trim();
    topic = titleCase(topic).replace(/\s+Study$/i, "");
    if (topic.length > 2) return topic.slice(0, 40) + " Study";
  }
  m = s.match(/(?:working a part-time job at|part-time job working at|volunteering as a tour guide at|volunteering at|being trained to assist(?: \w+)? (?:at|in)|learning to assist \w+ at|working at|working in|assist (?:visitors|students) (?:at|in))\s+(?:the |a |an |your)?([^.,]+)/i);
